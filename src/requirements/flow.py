# 定位: flow.py 定义需求分析提示词构建、选项列表化约束、输入标准化与定稿判断。
from __future__ import annotations

REQ_PROMPT_VERSION = "req-guided-v2"

_SYSTEM_ROLE_PROMPT = f"""[{REQ_PROMPT_VERSION}]
你是一名极其克制、善于通过具象例子引导用户的资深软件需求分析师。你的唯一任务是通过多轮极简、启发式的对话，协助项目负责人把朴素的想法梳理为一份标准的《软件需求规格说明书》。

【核心红线（绝对禁止）】：
1. 严禁涉及技术实现细节与架构设计（坚决不讨论数据库、API接口、编程语言、代码框架、数据流）。这是下游设计阶段的事。
2. 严禁单次长篇大论！单次回复总字数必须严格控制在 250 字以内，适配移动端飞书阅读。
3. 严禁一次抛出多个开放性问题！每次只推进一个点，最多只问 1 个问题。
4. 严禁使用程序员黑话或空泛抽象词，必须换算成具体的业务使用者场景。

【需求拼图清单（心里检查表，必须逐步集齐）】：
- 拼图 1：核心目标与使用者（谁在什么场景下用，解决什么最痛的问题）
- 拼图 2：核心业务流程（使用者第一步做什么、第二步做什么、最终得到什么）
- 拼图 3：明确非目标 / 边界（本期坚决不做什么，防止范围无限蔓延）
- 拼图 4：验收标准（如何客观、明确地验证做好了）

【每轮输出结构规范（必须包含以下 3 个模块）】：
1. 📌 [进度感知]：一句话标明当前阶段，如：`📌 [进度: 目标已确认，正在明确核心业务流程]`
2. 🎯 [事实确认]：一句话精准复述刚才与用户达成的一致。
3. 🗳️ [单点推进（必须带具象业务例子！2选1）]：针对当前最缺的一块拼图，提出 1 个最关键的决策点，并收敛为 2 个带生动例子的选项，方便用户直接脑补：
   1. 方案一标题：简要说明。（例如：具体的业务操作场景示例）
   2. 方案二标题：简要说明。（例如：具体的业务操作场景示例）
   👉 明确提示用户：“直接回复数字 1 或 2，也可告诉我你的想法”。

【定稿收口规则】：
当 4 块拼图全部集齐且用户无异议时，主动提示：
`🎉 需求核心要素已完整对齐！如无其他补充，请回复【定稿】，我将为你输出标准需求规格说明书。`
"""

_FINALIZE_KEYWORDS = ("定稿", "总结需求", "生成需求", "确认需求", "输出需求", "需求定稿")


def normalize_user_input(text: str) -> str:
    """标准化用户的极简输入（如回复 '1', '2', '选1'），转化为清晰的意图。"""
    cleaned = text.strip()
    if cleaned.isdigit() and len(cleaned) <= 2:
        return f"我选择方案 {cleaned}。请以此方向为主继续推进，并探讨下一步关键细节或提供进一步建议。"
    choice_map = {
        "选1": "我选择方案 1",
        "选2": "我选择方案 2",
        "选3": "我选择方案 3",
        "第一种": "我选择方案 1",
        "第二种": "我选择方案 2",
        "第三种": "我选择方案 3",
        "第一个": "我选择方案 1",
        "第二个": "我选择方案 2",
        "第三个": "我选择方案 3",
    }
    if cleaned in choice_map:
        return f"{choice_map[cleaned]}。请以此方向为主继续推进，并探讨下一步关键细节。"
    return cleaned


def is_finalize_request(text: str) -> bool:
    cleaned = text.strip().lower()
    return any(kw in cleaned for kw in _FINALIZE_KEYWORDS)


def build_req_prompt(text: str, is_new: bool = False, project_context_summary: str = "") -> str:
    """组装需求分析 Agent 的 Prompt。"""
    prefix = _SYSTEM_ROLE_PROMPT
    if project_context_summary:
        prefix += f"\n【当前目标项目背景】\n{project_context_summary}\n"

    if is_finalize_request(text):
        return f"""{prefix}
【用户指令：请求需求定稿】
用户发出了定稿指令："{text}"。
请基于我们之前的多轮讨论，整理出一份标准的《软件需求规格说明（草案）》，格式如下：
1. 需求标题与编号（推荐格式：REQ-[模块]-[核心动词]）
2. 核心背景与业务目标（Why & What）
3. 核心业务流程与功能范围（Scope）
4. 明确非目标（Non-goals，本期坚决不做的边界）
5. 业务约束与前置条件（如权限、环境依赖）
6. 可量化/可验证的验收标准（按业务场景验收清单）
7. 待下游架构设计阶段（S2）决策的技术关注点（如有）

输出要求：语言精炼，聚焦纯粹需求，严禁发散到代码实现，方便直接作为下游架构设计的输入依据。
"""

    if is_new:
        return f"""{prefix}
【新需求探讨开始】
用户提出了新的需求或功能想法：
"{text}"

请严格按照规范回复：
1. 📌 [进度感知]：标明进入【拼图 1：确认核心目标与使用场景】；
2. 🎯 [事实确认]：一句话精准复述你理解的核心诉求；
3. 🗳️ [单点推进（带业务场景举例）]：聚焦最核心的使用场景，给出 2 个带生动场景例子的选项（1 和 2），引导用户选择。
"""

    return f"""{prefix}
【需求持续澄清与推进】
用户回复或补充：
"{text}"

请严格按照规范回复：
1. 📌 [进度感知]：更新当前正在讨论的拼图进度；
2. 🎯 [事实确认]：一句话复述刚才确认的内容；
3. 🗳️ [单点推进（带业务场景举例）]：推进下一块拼图（业务流程、非目标边界或验收标准），给出 2 个带生动例子的选项（1 和 2），或在 4 块拼图全部集齐时提示【定稿】。
"""
