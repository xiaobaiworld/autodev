_FINALIZE_KEYWORDS = ("定稿", "总结需求", "生成需求", "确认需求", "输出需求", "需求定稿")
_PROTOTYPE_KEYWORDS = ("原型", "线框图", "界面图", "原型图", "画界面", "看界面", "界面长什么样", "做个原型", "做原型", "界面草图", "看原型")


def is_prototype_request(text: str) -> bool:
    """判断是否为要求查看或生成界面原型的指令。"""
    cleaned = text.strip().lower()
    return any(kw in cleaned for kw in _PROTOTYPE_KEYWORDS)


def normalize_user_input(text: str) -> str:
    """标准化用户的极简输入（如回复 '1', '2', '选1', '看原型'），转化为清晰的意图。"""
    cleaned = text.strip()
    if cleaned.isdigit() and len(cleaned) <= 2:
        return f"我选择方案 {cleaned}。请以此方向为主继续推进，并探讨下一步关键细节或提供进一步建议。"
    choice_map = {
        "选1": "我选择方案 1",
        "选2": "我选择方案 2",
        "选3": "我选择方案 3",
        "第一种": "我选择方案 1",
        "第二种": "我选择方案 2",
        "第三种": "我选择方案 3",
        "第一个": "我选择方案 1",
        "第二个": "我选择方案 2",
        "第三个": "我选择方案 3",
        "看原型": "我想看一下当前业务流程的外部界面原型（低保真线框图）。请用直观立体的文本线框图为我绘制当前界面的原型示例，展示页面布局、输入项与核心按钮。",
        "需要原型": "我想看一下当前业务流程的外部界面原型（低保真线框图）。请用直观立体的文本线框图为我绘制当前界面的原型示例，展示页面布局、输入项与核心按钮。",
        "做个原型": "我想看一下当前业务流程的外部界面原型（低保真线框图）。请用直观立体的文本线框图为我绘制当前界面的原型示例，展示页面布局、输入项与核心按钮。",
        "画个原型": "我想看一下当前业务流程的外部界面原型（低保真线框图）。请用直观立体的文本线框图为我绘制当前界面的原型示例，展示页面布局、输入项与核心按钮。",
    }
    if cleaned in choice_map:
        return choice_map[cleaned]
    return cleaned


def is_finalize_request(text: str) -> bool:
    cleaned = text.strip().lower()
    return any(kw in cleaned for kw in _FINALIZE_KEYWORDS)


def build_req_prompt(text: str, is_new: bool = False, project_context_summary: str = "") -> str:
    """组装需求分析 Agent 的 Prompt。"""
    prefix = _SYSTEM_ROLE_PROMPT
    if project_context_summary:
        prefix += f"\n【当前目标项目背景】\n{project_context_summary}\n"

    if is_finalize_request(text):
        return f"""{prefix}
【用户指令：请求需求定稿】
用户发出了定稿指令："{text}"。
请基于我们之前的多轮讨论，整理出一份标准的《软件需求规格说明（草案）》，严格遵循 SPEC-REQ-STANDARD-v1.0 格式：
1. 需求标识与元数据（编号、名称、提出人、分析师、归属项目、定稿时间）
2. 需求规模分类与需求关联网络（需求规模类别[Epic/Feature/Sub-feature/Enhancement]、模块归属、与其他需求的关系矩阵如 Parent/Depends-on/Relates-to/None）
3. 核心背景与业务目标 (Why & What)（业务背景、业务目标）
4. 业务用例与核心流程 (Scope)（按步骤清晰业务流程）
5. 明确非目标与边界 (Non-goals)（带 ❌ 标记的具体排除项）
6. 外部界面原型草图 (UI Wireframe)（使用 ```text 代码块绘制低保真线框图，包含标题栏、输入框、按钮、展示区）
7. 业务约束与前置依赖（权限角色、环境依赖、规则约束）
8. 可量化验收标准清单 (Acceptance Criteria)（场景 1、场景 2 等可验证用例）
9. 下游架构设计关注点（提炼给 S2 的考量，严禁包含代码或建表 SQL）

输出要求：语言精炼，聚焦纯粹需求，严禁发散到代码实现，方便直接作为下游架构设计的输入依据。
"""

    if is_prototype_request(text):
        return f"""{prefix}
【用户指令：请求外部界面原型示例】
用户希望查看当前功能的外部界面线框图："{text}"。

请严格按照规范回复：
1. 📌 [进度感知]：标明进入【界面原型感知：外部交互线框示例】；
2. 🎯 [界面场景说明]：一句话说明当前界面代表哪个核心业务环节（谁在什么场景下操作）；
3. 📱 [界面原型线框图]：使用 ```text 绘制一个立体、逼真的 ASCII/Unicode 文本线框原型（控制在 12 行以内，展示页面标题、输入控件、操作按钮、内容区）；
4. 🗳️ [单点推进（2选1）]：针对原型界面的关键交互设计，抛出 2 个带例子的改进或推进选项，末尾提示回复 1 或 2。
"""

    if is_new:
        return f"""{prefix}
【新需求探讨开始】
用户提出了新的需求或功能想法：
"{text}"

请严格按照规范回复：
1. 📌 [进度感知]：标明进入【拼图 1：确认核心目标与使用场景】；
2. 🎯 [事实确认与拓扑判断]：
   • 核心诉求：一句话精准复述你理解的核心业务诉求；
   • 🏷️ 需求规模：明确判断是大需求(Epic)、标准功能(Feature)还是子功能小需求(Sub-feature)；
   • 📂 模块归属：指出挂载在系统哪个主业务模块下；
   • 🔗 需求关联：明确与其他具体需求的关系（Parent/Depends-on/Relates-to/None）；
3. 🗳️ [单点推进（带业务场景举例）]：聚焦最核心的使用场景，给出 2 个带生动场景例子的选项（1 和 2），引导用户选择；末尾附带提示：“需要做个界面原型草图吗？随时回复【看原型】”。
"""

    return f"""{prefix}
【需求持续澄清与推进】
用户回复或补充：
"{text}"

请严格按照规范回复：
1. 📌 [进度感知]：更新当前正在讨论的拼图进度；
2. 🎯 [事实确认]：一句话复述刚才确认的内容（若涉及范围调整，适时复核规模、归属与关联）；
3. 🗳️ [单点推进（带业务场景举例）]：推进下一块拼图（业务流程、非目标边界或验收标准），给出 2 个带生动例子的选项（1 和 2），适时提示是否需要界面原型草图，或在 4 块拼图全部集齐时提示【定稿】。
"""
