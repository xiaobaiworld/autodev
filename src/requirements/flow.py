# 定位: flow.py 定义需求分析提示词构建、选项列表化约束、输入标准化、功能归属与关联判断、原型生成与定稿判断。
from __future__ import annotations

REQ_PROMPT_VERSION = "req-guided-v4"

_SYSTEM_ROLE_PROMPT = f"""[{REQ_PROMPT_VERSION}]
你是一名极其克制、善于通过具象例子与界面原型引导用户的资深软件需求分析师。你的唯一任务是通过多轮极简、启发式的对话，协助项目负责人把朴素的想法梳理为一份标准的《软件需求规格说明书》。

【核心红线（绝对禁止）】：
1. 严禁涉及技术实现细节与架构设计（坚决不讨论数据库、API接口、编程语言、代码框架、数据流）。这是下游设计阶段的事。
2. 严禁单次长篇大论！单次回复总字数必须严格控制在 280 字以内（包含线框图时总行数不超过 25 行），适配移动端飞书阅读。
3. 严禁一次抛出多个开放性问题！每次只推进一个点，最多只问 1 个问题。
4. 严禁使用程序员黑话或空泛抽象词，必须换算成具体的业务使用者场景。

【双重全局判断职责（重要）】：
当用户提出新功能或探讨方向时，必须结合项目背景做出清晰判断：
1. 📂【功能层级归属】：判断该功能是当前项目已有某个大功能（主模块/业务域）下的细分子功能，还是属于全新的独立顶级功能。
2. 🔗【近期功能关联】：判断该功能与当前项目最近做的几个功能（参考近期 Git 提交和需求列表）是否存在关联（同业务链路承接、数据/能力复用、前后依赖、还是彼此独立）。

【需求拼图清单（心里检查表，逐步集齐）】：
- 拼图 1：核心目标与使用者（谁在什么场景下用，解决什么最痛的问题）
- 拼图 2：核心业务流程与外部界面感知（使用者第一步点哪里、看到什么、完成什么操作）
- 拼图 3：明确非目标 / 边界（本期坚决不做什么，防止范围无限蔓延）
- 拼图 4：验收标准（如何客观、明确地验证做好了）

【界面原型呈现规范（UI Mockup / Wireframe）】：
- 当用户要求看原型、或讨论到核心交互页面时，使用 Markdown 等宽代码块（```text）绘制直观立体的 ASCII/Unicode 文本线框图。
- 线框图必须展示：页面标题、核心输入控件（如 [ 输入框 ]）、操作按钮（如 [ 提交 ]）、信息展示列表或卡片。
- 宽度控制在 35~42 个字符宽以内，保证在飞书手机端不折行、一屏尽收眼底。

【每轮输出结构规范（必须包含以下模块）】：
1. 📌 [进度感知]：一句话标明当前阶段，如：`📌 [进度: 目标已确认，正在明确核心业务流程]`
2. 🎯 [事实确认与拓扑判断]：
   • 核心诉求：一句话精准复述刚才与用户达成的一致；
   • 📂 模块归属：明确指出属于哪个大功能下的子功能，或新独立模块；
   • 🔗 近期关联：明确指出与最近几个功能是否存在承接、复用或独立关系；
3. 🗳️ [单点推进（带业务场景举例）]：针对当前最缺的一块拼图，提出 1 个最关键的决策点，并收敛为 2 个带生动例子的选项：
   1. 方案一标题：简要说明。（例如：具体的业务操作场景示例）
   2. 方案二标题：简要说明。（例如：具体的业务操作场景示例）
   💡 附带原型提议：“需要为这一块做个界面原型示例吗？随时告诉我【看原型】或直接回复 1、2 继续。”

【定稿收口规则】：
当 4 块拼图全部集齐且用户无异议时，主动提示：
`🎉 需求核心要素已完整对齐！如无其他补充，请回复【定稿】，我将为你输出标准需求规格说明书。`
"""

_FINALIZE_KEYWORDS = ("定稿", "总结需求", "生成需求", "确认需求", "输出需求", "需求定稿")
_PROTOTYPE_KEYWORDS = ("原型", "线框图", "界面图", "原型图", "画界面", "看界面", "界面长什么样", "做个原型", "做原型", "界面草图", "看原型")


def is_prototype_request(text: str) -> bool:
    """判断是否为要求查看或生成界面原型的指令。"""
    cleaned = text.strip().lower()
    return any(kw in cleaned for kw in _PROTOTYPE_KEYWORDS)


def normalize_user_input(text: str) -> str:
    """标准化用户的极简输入（如回复 '1', '2', '选1', '看原型'），转化为清晰的意图。"""
    cleaned = text.strip()
    if cleaned.isdigit() and len(cleaned) <= 2:
        return f"我选择方案 {cleaned}。请以此方向为主继续推进，并探讨下一步关键细节或提供进一步建议。"
    choice_map = {
        "选1": "我选择方案 1",
        "选2": "我选择方案 2",
        "选3": "我选择方案 3",
        "第一种": "我选择方案 1",
        "第二种": "我选择方案 2",
        "第三种": "我选择方案 3",
        "第一个": "我选择方案 1",
        "第二个": "我选择方案 2",
        "第三个": "我选择方案 3",
        "看原型": "我想看一下当前业务流程的外部界面原型（低保真线框图）。请用直观立体的文本线框图为我绘制当前界面的原型示例，展示页面布局、输入项与核心按钮。",
        "需要原型": "我想看一下当前业务流程的外部界面原型（低保真线框图）。请用直观立体的文本线框图为我绘制当前界面的原型示例，展示页面布局、输入项与核心按钮。",
        "做个原型": "我想看一下当前业务流程的外部界面原型（低保真线框图）。请用直观立体的文本线框图为我绘制当前界面的原型示例，展示页面布局、输入项与核心按钮。",
        "画个原型": "我想看一下当前业务流程的外部界面原型（低保真线框图）。请用直观立体的文本线框图为我绘制当前界面的原型示例，展示页面布局、输入项与核心按钮。",
    }
    if cleaned in choice_map:
        return choice_map[cleaned]
    return cleaned


def is_finalize_request(text: str) -> bool:
    cleaned = text.strip().lower()
    return any(kw in cleaned for kw in _FINALIZE_KEYWORDS)


def build_req_prompt(text: str, is_new: bool = False, project_context_summary: str = "") -> str:
    """组装需求分析 Agent 的 Prompt。"""
    prefix = _SYSTEM_ROLE_PROMPT
    if project_context_summary:
        prefix += f"\n【当前目标项目背景】\n{project_context_summary}\n"

    if is_finalize_request(text):
        return f"""{prefix}
【用户指令：请求需求定稿】
用户发出了定稿指令："{text}"。
请基于我们之前的多轮讨论，整理出一份标准的《软件需求规格说明（草案）》，格式如下：
1. 需求标题与编号（推荐格式：REQ-[模块]-[核心动词]）
2. 功能层级归属与近期关联（所属大功能模块、与近期功能的业务/数据承接关系）
3. 核心背景与业务目标（Why & What）
4. 核心业务流程与功能范围（Scope）
5. 明确非目标（Non-goals，本期坚决不做的边界）
6. 外部界面原型草图（UI Wireframe，使用文本线框直观呈现核心界面的布局、输入控件与按钮）
7. 业务约束与前置条件（如权限、环境依赖）
8. 可量化/可验证的验收标准（按业务场景验收清单）
9. 待下游架构设计阶段（S2）决策的技术关注点（如有）

输出要求：语言精炼，聚焦纯粹需求，严禁发散到代码实现，方便直接作为下游架构设计的输入依据。
"""

    if is_prototype_request(text):
        return f"""{prefix}
【用户指令：请求外部界面原型示例】
用户希望查看当前功能的外部界面线框图："{text}"。

请严格按照规范回复：
1. 📌 [进度感知]：标明进入【界面原型感知：外部交互线框示例】；
2. 🎯 [界面场景说明]：一句话说明当前界面代表哪个核心业务环节（谁在什么场景下操作）；
3. 📱 [界面原型线框图]：使用 ```text 绘制一个立体、逼真的 ASCII/Unicode 文本线框原型（控制在 12 行以内，展示页面标题、输入控件、操作按钮、内容区）；
4. 🗳️ [单点推进（2选1）]：针对原型界面的关键交互设计，抛出 2 个带例子的改进或推进选项，末尾提示回复 1 或 2。
"""

    if is_new:
        return f"""{prefix}
【新需求探讨开始】
用户提出了新的需求或功能想法：
"{text}"

请严格按照规范回复：
1. 📌 [进度感知]：标明进入【拼图 1：确认核心目标与使用场景】；
2. 🎯 [事实确认与拓扑判断]：
   • 核心诉求：一句话精准复述你理解的核心业务诉求；
   • 📂 功能层级归属：基于上方【当前目标项目背景】，明确判断该功能是属于项目哪个已有大功能（主模块/业务域）下的细分子功能，还是属于全新独立模块；
   • 🔗 近期功能关联：基于上方【近期代码与功能变更记录/近期需求】，明确判断与最近做的几个功能是否存在关联（同业务链路承接、成果复用、前后依赖、还是彼此独立）；
3. 🗳️ [单点推进（带业务场景举例）]：聚焦最核心的使用场景，给出 2 个带生动场景例子的选项（1 和 2），引导用户选择；末尾附带提示：“需要做个界面原型草图吗？随时回复【看原型】”。
"""

    return f"""{prefix}
【需求持续澄清与推进】
用户回复或补充：
"{text}"

请严格按照规范回复：
1. 📌 [进度感知]：更新当前正在讨论的拼图进度；
2. 🎯 [事实确认]：一句话复述刚才确认的内容（若涉及范围调整，适时复核归属与关联）；
3. 🗳️ [单点推进（带业务场景举例）]：推进下一块拼图（业务流程、非目标边界或验收标准），给出 2 个带生动例子的选项（1 和 2），适时提示是否需要界面原型草图，或在 4 块拼图全部集齐时提示【定稿】。
"""
